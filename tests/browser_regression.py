"""Optional end-to-end tests for the compact/live UI (no npm dependency).

    python -m pip install playwright
    python -m playwright install chromium
    python tests/browser_regression.py

Set CHROMIUM_EXECUTABLE to an existing Chromium path. FORCE_2D=1 explicitly
blocks the library CDN to test the fallback when offline. HTML_PATH can target
another built edition, such as standalone/terrain-laboratory.html.
The report always identifies the actual renderer and test loading mode.
"""
from playwright.sync_api import sync_playwright
from pathlib import Path
import json, os

ROOT = Path(__file__).resolve().parents[1]
HTML = Path(os.environ.get('HTML_PATH', ROOT / 'portable/terrain-laboratory.html'))
OUTPUT = ROOT / '.validation'
OUTPUT.mkdir(exist_ok=True)
results = []

def check(name, condition, detail=''):
    if not condition:
        raise AssertionError(name + ': ' + str(detail))
    results.append({'test': name, 'result': 'pass', 'detail': detail})
    print('PASS', name, flush=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_EXECUTABLE'),
        headless=True, args=['--enable-unsafe-swiftshader', '--use-angle=swiftshader'])
    page = browser.new_page(viewport={'width': 1440, 'height': 960})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    if os.environ.get('FORCE_2D') == '1':
        page.route('https://cdn.jsdelivr.net/**', lambda route: route.abort())
    # No test-only implementation replaces application code or Worker behavior.
    page.set_content(HTML.read_text(), wait_until='domcontentloaded')

    def idle():
        page.wait_for_function('window.terrainLab && !terrainLab.getState().busy && terrainLab.getState().current', timeout=45000)
        assert not page.locator('#status').evaluate('(el) => el.classList.contains("error")'), page.locator('#status').inner_text()

    def current_hash(which='current'):
        return page.evaluate('''(which) => {
          const map = terrainLab.getState()[which]; if (!map) return null;
          const ints = new Uint32Array(map.data.buffer); let h = 2166136261;
          for (const x of ints) h = Math.imul(h ^ x, 16777619); return h >>> 0;
        }''', which)

    def seed():
        return page.locator('#base-seed').input_value()

    def accordion(name, expanded):
        toggle = page.locator(f'#{name}-settings-toggle')
        if (toggle.get_attribute('aria-expanded') == 'true') != expanded:
            toggle.click()

    def field(root, key, value):
        exact = page.locator(f'{root} [data-parameter="{key}"]')
        if exact.count():
            exact.fill(str(value)); return
        control = page.locator(f'{root} [name="{key}"]')
        if control.evaluate('(el) => el.tagName') == 'SELECT':
            control.select_option(str(value))
        else:
            control.fill(str(value))

    def choose(family, algorithm):
        page.select_option('#family', family)
        page.select_option('#algorithm', algorithm)
        idle()

    def erosion_settings(algorithm, overrides):
        accordion('erosion', True)
        page.locator(f'#erosion-{algorithm}').evaluate('(el) => el.open = true')
        for key, value in overrides.items():
            field(f'#parameters-{algorithm}', key, value)

    idle()
    backend = page.evaluate('terrainLab.getRendererInfo().backend')
    check('Default 257×257 terrain is generated by the real worker', page.evaluate('terrainLab.getState().current.width') == 257)
    check('Both advanced accordions start collapsed', page.locator('#base-settings').is_hidden() and page.locator('#erosion-settings').is_hidden())
    check('Base quick view contains only two selectors and Generate', page.locator('#base-controls input:visible').count() == 0 and page.locator('#base-controls select:visible').count() == 2 and page.locator('#generate').is_visible())
    check('All three erosion types can be applied without expanding settings', all(page.locator(f'#apply-{id}').is_visible() for id in ['droplet', 'grid', 'thermal']))
    check('Main accordions have explicit More settings affordances', page.locator('.section-toggle .settings-label').all_text_contents() == ['More settings', 'More settings'])
    check('Undo/reset stay out of the empty quick view', page.locator('#erosion-history').is_hidden())
    first_seed = seed(); first_map = current_hash()
    page.click('#generate'); idle()
    second_seed = seed(); second_map = current_hash()
    page.click('#generate'); idle()
    check('Every Generate click picks a new string seed', len({first_seed, second_seed, seed()}) == 3 and seed().startswith('terrain-'))
    check('Repeated Generate clicks produce fresh terrain', len({first_map, second_map, current_hash()}) == 3)
    check('Displayed recipe records the latest generated seed', page.evaluate('terrainLab.getState().baseRecipe.parameters.seed') == seed())
    # Keyboard-accessible advanced controls and linked exact-value widgets.
    page.locator('#base-settings-toggle').focus(); page.keyboard.press('Enter')
    check('Keyboard activation expands the terrain settings', page.locator('#base-settings').is_visible() and page.locator('#base-settings-toggle').get_attribute('aria-expanded') == 'true')
    check('Expanded header says Hide settings', page.locator('#base-settings-toggle .settings-label').inner_text() == 'Hide settings')
    current_seed = seed(); before = current_hash()
    field('#base-parameters', 'frequency', 7); idle()
    check('Base parameter edits generate live without clicking Generate', current_hash() != before and page.evaluate('terrainLab.getState().baseRecipe.parameters.frequency') == 7)
    check('Live edits keep the same seed', seed() == current_seed)
    check('Slider and precise number stay synchronized', page.locator('#base-parameters [name="frequency"]').input_value() == '7')
    page.locator('#base-parameters [name="frequency"]').evaluate('el => { el.value = 5; el.dispatchEvent(new Event("input", {bubbles:true})); }'); idle()
    check('Dragging a range input updates its exact number and the terrain', page.locator('#base-parameters [data-parameter="frequency"]').input_value() == '5' and page.evaluate('terrainLab.getState().baseRecipe.parameters.frequency') == 5)
    # A saved seed can still reproduce the same terrain exactly.
    page.fill('#base-seed', 'repeatable-demo'); idle(); reproducible = current_hash()
    page.fill('#base-seed', 'a-different-demo'); idle()
    check('Typing a seed updates the terrain live', current_hash() != reproducible)
    page.fill('#base-seed', 'repeatable-demo'); idle()
    check('Pasting a previous seed reproduces its exact heightmap', current_hash() == reproducible)
    page.select_option('#segments', '128'); idle()
    check('Resolution selection updates live', page.evaluate('terrainLab.getState().current.width') == 129)
    page.fill('#terrain-size', '320'); idle()
    check('World-size input updates live and stays linked to its slider', page.evaluate('terrainLab.getState().current.size') == 320 and page.locator('#terrain-size-slider').input_value() == '320')
    page.fill('#terrain-size', '256'); idle()
    # Invalid draft values preserve both base and current data, without popups.
    unchanged = current_hash()
    field('#base-parameters', 'frequency', ''); page.wait_for_timeout(250)
    check('An unfinished numeric input preserves current terrain', current_hash() == unchanged and not page.evaluate('terrainLab.getState().busy'))
    field('#base-parameters', 'frequency', 6); idle()
    check('Finishing a valid value resumes live updates', page.evaluate('terrainLab.getState().baseRecipe.parameters.frequency') == 6)
    page.fill('#terrain-size', '1'); page.wait_for_timeout(220)
    check('Out-of-range world size never reaches the heightmap', page.evaluate('terrainLab.getState().current.size') == 256)
    page.fill('#terrain-size', '256'); idle()
    # Selections also update live, while retaining per-technique parameter values.
    families = {'perlin':'gradient', 'simplex':'gradient', 'fbm':'gradient', 'ridged':'gradient', 'warp':'gradient',
                'diamondSquare':'recursive', 'voronoi':'cellular', 'worley':'cellular', 'fault':'geological', 'tectonic':'geological'}
    hashes = []
    for algorithm, family in families.items():
        same_seed = seed(); choose(family, algorithm)
        hashes.append(current_hash())
        check(f'{algorithm}: live selection runs its actual generator and keeps the seed', page.evaluate('terrainLab.getState().baseRecipe.algorithm') == algorithm and seed() == same_seed)
        check(f'{algorithm}: all bounded numeric controls use paired sliders', page.locator('#base-parameters input[type=number]').count() == page.locator('#base-parameters input[type=range]').count())
    check('Ten algorithms still produce distinct terrain', len(set(hashes)) == 10)
    choose('gradient', 'fbm')
    check('Switching techniques retains their parameter settings', page.locator('#base-parameters [data-parameter="frequency"]').input_value() == '6')
    choose('gradient', 'warp')
    check('Warped fBm hides irrelevant ridge controls', not page.locator('#base-parameters [name=sharpness]').is_visible())
    field('#base-parameters', 'warpMode', 'ridged'); idle()
    check('Warped ridges reveal relevant controls and regenerate live', page.locator('#base-parameters [name=sharpness]').is_visible() and page.evaluate('terrainLab.getState().baseRecipe.parameters.warpMode') == 'ridged')
    choose('gradient', 'fbm'); original = current_hash()
    accordion('base', False)
    check('Collapsing settings does not change the terrain', current_hash() == original)
    # Erosion configuration stays manual, and quick buttons use those settings.
    erosion_settings('thermal', {'iterations': 40, 'talusAngle': 10})
    page.wait_for_timeout(250)
    check('Erosion parameter edits never regenerate or erode terrain', current_hash() == original and not page.evaluate('terrainLab.getState().busy'))
    accordion('erosion', False)
    page.click('#apply-thermal'); idle(); first = current_hash()
    check('Collapsed thermal action changes only the current heightmap', first != original and current_hash('base') == original)
    check('Undo and reset appear after applying erosion', page.locator('#undo').is_visible() and page.locator('#reset').is_visible())
    erosion_settings('droplet', {'droplets': 1500, 'lifetime': 64})
    accordion('erosion', False); page.click('#apply-droplet'); idle(); second = current_hash()
    check('Collapsed droplet action accumulates on thermal output', second != first and current_hash('base') == original)
    erosion_settings('grid', {'iterations': 35})
    accordion('erosion', False); page.click('#apply-grid'); idle(); third = current_hash()
    check('Collapsed grid action accumulates independently', third != second and current_hash('base') == original)
    check('Three erosion snapshots are retained', page.evaluate('terrainLab.getState().historyLength') == 3)
    page.click('#undo'); check('Undo grid exactly restores droplet output', current_hash() == second)
    page.click('#undo'); check('Undo droplets exactly restores thermal output', current_hash() == first)
    page.check('#show-base'); check('Show base comparison remains nondestructive', current_hash() == first)
    page.uncheck('#show-base'); page.click('#reset')
    check('Reset exactly restores base and clears history', current_hash() == original and page.evaluate('terrainLab.getState().historyLength') == 0)
    page.click('#apply-thermal'); idle()
    accordion('base', True); field('#base-parameters', 'frequency', 8); idle()
    check('A live base edit clears applied erosion and establishes a new base', current_hash() == current_hash('base') and page.evaluate('terrainLab.getState().historyLength') == 0)
    # Exercise latest-wins worker cancellation during a slow generator.
    choose('geological', 'fault')
    field('#base-parameters', 'iterations', 2000)
    page.select_option('#segments', '512')
    page.evaluate('window.heartbeat = 0; window.heartbeatTimer = setInterval(() => heartbeat++, 10)')
    page.wait_for_function('terrainLab.getState().generationRunning && document.getElementById("progress").value > 0', timeout=15000)
    check('Base controls remain editable while a slow generator is running', not page.locator('#base-controls').evaluate('(el) => el.disabled'))
    check('Erosion actions are disabled while base generation is running', page.locator('#apply-thermal').is_disabled())
    check('Worker generation leaves the UI responsive', page.evaluate('heartbeat') > 1)
    page.select_option('#segments', '128')
    choose('gradient', 'perlin')
    latest = current_hash(); page.wait_for_timeout(300)
    page.evaluate('clearInterval(heartbeatTimer)')
    check('New live edits cancel and supersede a running generator', current_hash() == latest and page.evaluate('terrainLab.getState().current.width') == 129 and page.evaluate('terrainLab.getState().baseRecipe.algorithm') == 'perlin')
    # A burst is coalesced, and only its final parameter value is committed.
    page.locator('#base-parameters [name=frequency]').evaluate('''el => {
      for (let i = 1; i <= 10; i++) { el.value = i; el.dispatchEvent(new Event('input', {bubbles:true})); }
    }'''); idle()
    check('Rapid slider input commits the latest value', page.evaluate('terrainLab.getState().baseRecipe.parameters.frequency') == 10)
    old_seed = seed()
    clicked_seeds = page.evaluate('''() => {
      const seeds = [];
      for (let i = 0; i < 4; i++) { document.getElementById('generate').click(); seeds.push(document.getElementById('base-seed').value); }
      return seeds;
    }'''); idle()
    check('Rapid Generate clicks each randomize and commit only the latest recipe', len(set([old_seed] + clicked_seeds)) == 5 and page.evaluate('terrainLab.getState().baseRecipe.parameters.seed') == clicked_seeds[-1])
    # Cancel a scheduled update before it starts; no partial state is committed.
    before_cancel = current_hash()
    page.evaluate('''() => {
      const input = document.querySelector('#base-parameters [name=frequency]');
      input.value = 9; input.dispatchEvent(new Event('input', {bubbles:true}));
      document.getElementById('cancel').click();
    }'''); idle(); page.wait_for_timeout(250)
    check('Cancel during the live debounce preserves exact terrain', current_hash() == before_cancel)
    # High-resolution erosion is also cancelable without altering history.
    choose('gradient', 'fbm'); page.select_option('#segments', '512'); idle()
    check('513×513 high-resolution generation still works', page.evaluate('terrainLab.getState().current.width') == 513)
    high = current_hash()
    erosion_settings('thermal', {'iterations': 2000})
    page.click('#apply-config-thermal')
    page.wait_for_function('terrainLab.getState().busy && document.getElementById("progress").value > 0', timeout=15000)
    check('Base controls are locked only while applying erosion', page.locator('#base-controls').evaluate('(el) => el.disabled'))
    page.click('#cancel'); idle()
    check('Canceled erosion preserves current, base, and undo history', current_hash() == high and current_hash('base') == high and page.evaluate('terrainLab.getState().historyLength') == 0)
    # Export and responsive layout checks.
    accordion('erosion', False); page.select_option('#segments', '128'); idle()
    accordion('base', False)
    page.locator('#notes-panel').evaluate('(el) => el.open = true')
    with page.expect_download() as download:
        page.click('#export-json')
    download.value.save_as(str(OUTPUT / 'test-heightmap-export.json'))
    exported = json.loads((OUTPUT / 'test-heightmap-export.json').read_text())
    check('JSON export keeps the actual live recipe and full heightmap', len(exported['elevations']) == 129**2 and exported['baseRecipe']['parameters']['seed'] == seed())
    with page.expect_download() as download:
        page.click('#export-png')
    download.value.save_as(str(OUTPUT / 'test-heightmap-export.png'))
    check('Grayscale PNG export still downloads', (OUTPUT / 'test-heightmap-export.png').stat().st_size > 100)
    page.locator('#notes-panel').evaluate('(el) => el.open = false')
    page.locator('#controls').evaluate('(el) => el.scrollTop = 0')
    page.screenshot(path=str(OUTPUT / 'desktop-compact.png'))
    check('Compact desktop controls fit without sidebar scrolling', page.locator('#controls').evaluate('(el) => el.scrollHeight <= el.clientHeight'))
    accordion('base', True)
    page.locator('#controls').evaluate('(el) => el.scrollTop = 0')
    page.screenshot(path=str(OUTPUT / 'desktop-expanded.png'))
    accordion('base', False)
    page.set_viewport_size({'width': 412, 'height': 915})
    page.screenshot(path=str(OUTPUT / 'mobile-compact.png'), full_page=True)
    check('Mobile compact layout has no horizontal overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    accordion('erosion', True)
    page.locator('#erosion-droplet').evaluate('(el) => el.open = true')
    check('Advanced mobile sliders also fit without horizontal overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    check('No uncaught JavaScript exceptions', not errors, errors)
    browser.close()

report = {
    'version': '1.1.0', 'backend': backend, 'testsPassed': len(results), 'tests': results,
    'loadingMode': 'Built HTML injected into a real Chromium page with set_content; real Blob Web Workers.',
    'forcedFallback': os.environ.get('FORCE_2D') == '1',
    'limitations': ('Canvas2D checks do not verify Three.js/WebGL rendering.' if backend == 'Canvas2D' else 'UI/state/worker tests are not a complete visual rendering audit.')
      + ' Vite build, offline export, and direct file:// launch are outside the scope of this test run.'
}
(OUTPUT / 'browser-validation.json').write_text(json.dumps(report, indent=2))
print(json.dumps({'backend': backend, 'passed': len(results), 'errors': errors}, indent=2))
